import { randomBytes } from "node:crypto";
import { writeFile } from "node:fs/promises";

const path = new URL("../.dev.vars", import.meta.url);
const expiresAt = new Date(Date.now() + 60 * 60 * 1000).toISOString();
const values = {
  AUTH_ORIGIN: "http://localhost:5173",
  AUTH_SECRET: randomBytes(48).toString("base64url"),
  OPERATOR_BOOTSTRAP_SECRET: randomBytes(32).toString("base64url"),
  OPERATOR_BOOTSTRAP_EXPIRES_AT: expiresAt,
  MAIL_FROM: "vaskel@example.invalid",
  REALTIME_APP_ID: "",
  REALTIME_APP_SECRET: "",
};

try {
  await writeFile(
    path,
    "# Local secrets; generated by pnpm run dev:setup. Do not commit.\n" +
      Object.entries(values)
        .map(([name, value]) => `${name}=${JSON.stringify(value)}`)
        .join("\n") +
      "\n",
    { flag: "wx", mode: 0o600 },
  );
  console.log(`Created .dev.vars. Bootstrap expires at ${expiresAt}.`);
  console.log(
    "Email uses local simulation. Configure a sending domain before deployment. Secrets were not printed.",
  );
} catch (error) {
  if (error instanceof Error && "code" in error && error.code === "EEXIST") {
    console.error(".dev.vars already exists; it was not changed.");
    process.exitCode = 1;
  } else {
    throw error;
  }
}
